"""Shared versus session-owned sidebar behavior on isolated real tmux servers."""
from support import StickyTestCase


class StickyShared(StickyTestCase):
    def test_shared_pane_automatically_follows_its_interactive_client(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        self.tmux("split-window", "-d", "-h", "-t", self.target, "sleep", "600")
        human = self.attach(self.session)
        before = self.info(self.target, "window_layout")
        self.install()
        opened = self.show()
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.tmux("switch-client", "-c", human, "-t", self.info(other, "session_id"))
        self.eventually(lambda: self.assertEqual(self.info(opened["pane"], "window_id"), self.info(other, "window_id")))
        self.eventually(lambda: self.assertEqual(self.info(self.target, "window_layout"), before))
        self.assertEqual(self.status(other)["pid"], opened["pid"])
        self.assertEqual(self.info(other, "pane_active"), "1")

    def test_enabling_shared_mode_adopts_the_parked_process(self):
        opened = self.show()
        self.cli("hide")
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        adopted = self.status()
        self.assertEqual(adopted["state"], "parked")
        self.assertEqual((adopted["pane"], adopted["pid"]), (opened["pane"], opened["pid"]))
        survivor = self.tmux("new-session", "-d", "-s", "survivor", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.tmux("kill-session", "-t", self.session)
        self.cli("cleanup")
        self.cli("show", "--target", survivor)
        self.assertEqual(self.status(survivor)["pid"], opened["pid"])

    def test_background_clients_cannot_claim_or_move_the_shared_pane(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        human = self.attach(self.session)
        self.install()
        opened = self.show()
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        monitor = self.attach(self.info(other, "session_id"), control=True)
        self.tmux("switch-client", "-c", monitor, "-t", self.session)
        self.cli("follow-client", monitor)
        self.tmux("switch-client", "-c", monitor, "-t", self.info(other, "session_id"))
        self.cli("follow-client", monitor)
        state = self.status()
        self.assertEqual(state["client"], human)
        self.assertEqual(state["pid"], opened["pid"])
        self.assertEqual(self.info(opened["pane"], "window_id"), self.window)

    def test_hidden_shared_pane_stays_hidden_when_switching_sessions(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        human = self.attach(self.session)
        self.install()
        opened = self.show()
        self.cli("hide")
        parking = self.info(opened["pane"], "window_id")
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.tmux("switch-client", "-c", human, "-t", self.info(other, "session_id"))
        self.cli("follow-client", human)
        self.assertEqual(self.status(other)["state"], "parked")
        self.assertEqual(self.info(opened["pane"], "window_id"), parking)
        self.cli("toggle", "--target", other, "--client", human)
        self.assertEqual(self.status(other)["pid"], opened["pid"])
        self.assertEqual(self.info(opened["pane"], "window_id"), self.info(other, "window_id"))

    def test_another_human_must_explicitly_take_over_the_shared_pane(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        first = self.attach(self.session)
        self.install()
        opened = self.show()
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        second_session = self.info(other, "session_id")
        second = self.attach(second_session)
        self.cli("follow-client", second)
        self.assertEqual(self.status()["client"], first)
        self.assertEqual(self.info(opened["pane"], "window_id"), self.window)
        self.cli("toggle", "--target", other, "--client", second)
        self.assertEqual(self.status(other)["state"], "visible")
        self.assertEqual(self.status(other)["client"], second)
        self.assertEqual(self.info(opened["pane"], "window_id"), self.info(other, "window_id"))
        self.tmux("switch-client", "-c", first, "-t", second_session)
        self.tmux("switch-client", "-c", first, "-t", self.session)
        self.cli("follow-client", first)
        self.assertEqual(self.info(opened["pane"], "window_id"), self.info(other, "window_id"))

    def test_off_mode_keeps_independent_sidebars_during_session_switches(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "off")
        human = self.attach(self.session)
        self.install()
        first = self.show()
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.cli("show", "--target", other, "--", "sleep", "600")
        second = self.status(other)
        self.tmux("switch-client", "-c", human, "-t", self.info(other, "session_id"))
        self.cli("follow-client", human)
        self.assertNotEqual(first["pane"], second["pane"])
        self.assertEqual(self.info(first["pane"], "session_id"), self.session)
        self.assertEqual(self.info(second["pane"], "session_id"), self.info(other, "session_id"))

    def test_visible_session_pane_can_be_adopted_without_layout_changes(self):
        self.tmux("split-window", "-d", "-h", "-t", self.target, "sleep", "600")
        before = self.info(self.target, "window_layout")
        opened = self.show()
        visible = self.info(self.target, "window_layout")
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        adopted = self.status()
        self.assertEqual(adopted["pid"], opened["pid"])
        self.assertEqual(self.info(self.target, "window_layout"), visible)
        self.cli("hide")
        self.assertEqual(self.info(self.target, "window_layout"), before)
        self.assertEqual(self.status()["state"], "parked")

    def test_shared_window_follow_uses_the_bound_clients_selected_window(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        self.attach(self.session)
        self.install()
        before = self.info(self.target, "window_layout")
        opened = self.show()
        other = self.tmux("new-window", "-t", self.session, "-P", "-F", "#{pane_id}", "sleep", "600")
        self.eventually(lambda: self.assertEqual(self.info(opened["pane"], "window_id"), self.info(other, "window_id")))
        self.eventually(lambda: self.assertEqual(self.info(self.target, "window_layout"), before))
        self.assertEqual(self.status(other)["pid"], opened["pid"])

    def test_sharing_does_not_close_a_source_session_with_only_the_sidebar(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        human = self.attach(self.session)
        self.install()
        opened = self.show()
        self.tmux("kill-pane", "-t", self.target)
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.tmux("switch-client", "-c", human, "-t", self.info(other, "session_id"))
        self.cli("follow-client", human, check=False)
        self.assertIn(self.session, self.tmux("list-sessions", "-F", "#{session_id}").splitlines())
        self.assertEqual(self.info(opened["pane"], "session_id"), self.session)

    def test_existing_shared_instance_can_be_closed_after_switching_mode_off(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        opened = self.show()
        self.cli("hide")
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "off")
        self.assertEqual(self.status()["scope"], "session")
        self.assertEqual(self.cli("status", "--scope", "shared").returncode, 0)
        self.cli("kill", "--scope", "shared")
        self.assertNotIn(opened["pane"], self.tmux("list-panes", "-a", "-F", "#{pane_id}").splitlines())

    def test_shared_show_reuses_one_process_across_sessions(self):
        self.tmux("set-option", "-g", "@sticky-follow-sessions", "on")
        self.tmux("split-window", "-d", "-h", "-t", self.target, "sleep", "600")
        before = self.info(self.target, "window_layout")
        opened = self.show()
        other = self.tmux("new-session", "-d", "-s", "second", "-P", "-F", "#{pane_id}", "sleep", "600")
        self.cli("show", "--target", other)
        moved = self.status(other)
        self.assertEqual((moved["pane"], moved["pid"]), (opened["pane"], opened["pid"]))
        self.assertEqual(self.info(opened["pane"], "session_id"), self.info(other, "session_id"))
        self.assertEqual(self.info(self.target, "window_layout"), before)
        self.cli("hide", "--target", other)
        self.cli("show", "--target", self.target)
        self.assertEqual(self.status()["pid"], opened["pid"])
